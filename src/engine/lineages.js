// Names and order from William's docs/ants-top-50.md. Bonuses are game rules,
// not claims about the biology of these species.
export function lineageFor(generation = 0) {
  const rank = 50 - (generation % 50),
    ant = ANT_LINEAGES[rank - 1];
  return { ...ant, generation, cycle: Math.floor(generation / 50) + 1 };
}
export function lineageBoost(state, branch) {
  const generation = state.lineage.generation;
  const ant = ANT_LINEAGES[49 - (generation % 50)];
  return (
    1 +
    generation * 0.035 +
    (generation > 0 && ant.affinity === branch ? 0.08 : 0)
  );
}
export function lineageView(state) {
  const current = lineageFor(state.lineage.generation),
    next = lineageFor(current.generation + 1);
  const names = {
    foraging: "food carrying and travel",
    brood: "egg development",
    excavation: "digging and energy recovery",
    military: "combat strength",
    founding: "starting supplies",
  };
  return {
    current,
    next,
    label: `Rank ${current.rank} · ${current.name}`,
    detail:
      current.generation === 0
        ? "Your first lineage. Complete this colony to unlock the next ant."
        : `+${Math.round(current.generation * 3.5)}% to colony systems; +8% to ${names[current.affinity]}.`,
    nextDetail: `Next colony: ${next.name} · rank ${next.rank} · cycle ${next.cycle}`,
    collection: ANT_LINEAGES.map((ant) => ({
      ...ant,
      unlocked: current.generation >= 50 - ant.rank,
      current: current.rank === ant.rank,
      specialty: names[ant.affinity],
    })),
    unlocked: Math.min(50, current.generation + 1),
  };
}
